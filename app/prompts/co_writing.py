def mode_block_for(stage: str, mode: str, user_message: str) -> str:
    """对话回应模式块：讨论（默认，硬约束短回复）/ 撰写（产出草案）。

    讨论模式的字数上限随输入长度收缩：短输入（≤12 字）配 80 字上限——
    「发两三个字收七百字」是共写体验最重的伤（真机验证 P0-1）。
    """
    if mode == "compose":
        block = COMPOSE_MODE_BLOCK
        if stage == "cw_prose":
            # C1 落稿契约：正文必须包裹在标记内，提取器据此剥出正文存盘，
            # 开场白与元话语不再混进正文文件
            block += ("正文草案必须用以下标记完整包裹（标记独立成行）：\n"
                      "<<<正文>>>\n（正文全文，首行为「## 第N章 章名」标题）\n"
                      "<<<正文完>>>\n")
        return block
    text = (user_message or "").strip()
    cap = 80 if len(text) <= 12 else 200
    return DISCUSS_MODE_BLOCK.format(user_message=text, word_cap=cap)


