def build_upstream_anchors(proj, num):
    """构建上游产物行号锚定块（供 ROOT_CAUSE_PROMPT 注入）。

    延迟 import 避免循环依赖（prompts 在 app/__init__ 加载早期就被引用）。
    """
    import os
    from app import project as prj_mod
    blocks = []

    def _anchor(label, rel_path, max_lines=80):
        path = os.path.join(proj, rel_path)
        if not os.path.isfile(path):
            return
        try:
            text = prj_mod.read_file(path)
        except Exception:
            return
        lines = (text or "").splitlines()[:max_lines]
        anchored = "\n".join(f"L{i+1}: {line}" for i, line in enumerate(lines))
        blocks.append(f"【{label} · 锚定行号】\n{anchored}")

    _anchor("核心设定", "设定/题材定位.md", 50)
    _anchor("大纲", "大纲/大纲.md", 80)
    _anchor(f"细纲 · 第{num}章", f"大纲/细纲_第{num:03d}章.md", 30)
    _anchor("世界书", "设定/世界书.md", 60)
    _anchor("正则", "设定/正则.md", 30)
    _anchor("已锁章节摘要（参考）", "追踪/章节摘要.md", 20)

    return "\n\n".join(blocks) if blocks else "（无上游产物）"


def build_issues_brief(issues):
    """issues 列表 → 紧凑文本（注入 ROOT_CAUSE_PROMPT）。

    issues: list of dict [{dim, level, text, quote, root_layer}, ...]
    """
    if not issues:
        return "（无 issues）"
    lines = []
    for i, issue in enumerate(issues, 1):
        if isinstance(issue, dict):
            lines.append(
                f"[{i}] dim={issue.get('dim','?')} level={issue.get('level','?')} "
                f"text={issue.get('text','')[:80]} quote={issue.get('quote','')[:60]}"
            )
        else:
            lines.append(f"[{i}] {str(issue)[:120]}")
    return "\n".join(lines)

