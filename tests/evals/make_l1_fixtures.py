def fixture_project_path(preset_id: str) -> str:
    return os.path.join(FIXTURES, preset_id, "proj", "预设测试书")


def generate() -> int:
    n = 0
    for preset_id, files in FIXTURES_TREE.items():
        proj = fixture_project_path(preset_id)
        for rel, content in files.items():
            sub, name = rel.split("/", 1)
            d = os.path.join(proj, sub)
            os.makedirs(d, exist_ok=True)
            path = os.path.join(d, name + ".md")
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(content.strip() + "\n")
            n += 1
    print(f"已生成 {n} 个夹具文件 → {FIXTURES}")
    return 0


def _norm(t: str) -> str:
    import re
    return re.sub(
        r"[\s\.\,\!\?\:\;\u3002\uff0c\uff01\uff1f\uff1a\uff1b\u201c\u201d\u300a\u300b'\"]+",
        "", t)


def check() -> int:
    """校验：每条 L1 金标的 real_text 必须能在对应夹具章节中找到"""
    import json
    gold = json.load(open(os.path.join(HERE, "gold_set.json"), encoding="utf-8"))
    bad = []
    for g in gold:
        if g.get("type") != "l1":
            continue
        preset = g.get("source_preset", "")
        chap = g.get("source_chapter", 0)
        text_path = os.path.join(fixture_project_path(preset), "正文", f"第{chap:03d}章.md")
        if not os.path.isfile(text_path):
            bad.append((g["id"], "夹具章节缺失"))
            continue
        prose = open(text_path, encoding="utf-8").read()
        if _norm(g.get("real_text", "")) not in _norm(prose):
            bad.append((g["id"], "real_text 未嵌入"))
    if bad:
        print("校验失败:")
        for gid, why in bad:
            print(f"  - {gid}: {why}")
        return 1
    print("校验通过：15 条 L1 金标 real_text 全部嵌入夹具")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只校验，不生成")
    args = ap.parse_args()
    if args.check:
        sys.exit(check())
    sys.exit(generate())


if __name__ == "__main__":
    main()
